"""Generate content-addressed web media; preserve all original files. Requires existing ffmpeg."""
from pathlib import Path
import subprocess, hashlib, json
root = Path(__file__).resolve().parents[1]
public = root / 'public'
image_dir = public / 'images' / 'optimized'
video_dir = public / 'videos' / 'optimized'
image_dir.mkdir(parents=True, exist_ok=True)
video_dir.mkdir(parents=True, exist_ok=True)
images = {}
thumbnails = {}
source_images = list((public/'images'/'products'/'scenes-v2').glob('*.webp'))
source_images += list((public/'images'/'applications').glob('*.png'))
source_images += list((public/'images'/'capabilities').glob('*.png'))
source_images += [public/'images/hyper/cyberport.png', public/'images/home/glp-field.jpg', public/'images/generated/glp-robot-inspection-poster.jpg', public/'images/capabilities/autonomous-patrol-poster.jpg', public/'videos/haiforce-hero-poster.jpg', public/'images/generated/hyper-hero-robotics.png']

def encode(source, dest, args):
    subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-i',str(source),*args,str(dest)],check=True)
    digest = hashlib.sha256(dest.read_bytes()).hexdigest()[:12]
    final = dest.with_name(f'{dest.stem}-{digest}{dest.suffix}')
    dest.replace(final)
    print(f'{source.name}: {source.stat().st_size} -> {final.stat().st_size}',flush=True)
    return '/'+final.relative_to(public).as_posix()

for src in source_images:
    if not src.exists(): continue
    key = '/'+src.relative_to(public).as_posix()
    images[key] = encode(src,image_dir/f'{src.stem}.webp',['-vf',"scale='min(1600,iw)':-2",'-frames:v','1','-c:v','libwebp','-quality','80'])
    if 'scenes-v2' in src.parts:
        thumbnails[key] = encode(src,image_dir/f'{src.stem}-thumb.webp',['-vf','scale=96:-2','-frames:v','1','-c:v','libwebp','-quality','70'])
# Make image mappings available independently of the longer video encoding.
(root/'lib/media.ts').write_text('// Generated by scripts/optimize-media.py; originals remain untouched.\nconst images: Record<string, string> = '+json.dumps(images,indent=2)+';\nconst thumbnails: Record<string, string> = '+json.dumps(thumbnails,indent=2)+';\nexport function imageSrc(src: string, thumbnail = false) { return (thumbnail ? thumbnails[src] : images[src]) ?? images[src] ?? src; }\n')
videos = {}
for key, filename, width in [('heroDesktop','haiforce-hero.mp4',1280),('heroMobile','haiforce-hero.mp4',854),('patrol','field/obstacles.mp4',854),('caseStudy','glp-robot-inspection.mp4',1280)]:
    src = public/'videos'/filename
    videos[key] = encode(src,video_dir/f'{key}.mp4',['-vf',f"scale='min({width},iw)':-2",'-r','24','-c:v','libx264','-preset','fast','-crf','28' if key == 'patrol' else '26','-maxrate','1200k' if key == 'patrol' else '2400k','-bufsize','2400k' if key == 'patrol' else '4800k','-threads','2','-an','-pix_fmt','yuv420p','-g','48','-movflags','+faststart'])
with (root/'lib/media.ts').open('a') as f: f.write('export const videos = '+json.dumps(videos,indent=2)+' as const;\n')
